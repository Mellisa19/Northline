def allowed_origins() -> list[str]:
    """Origins allowed to call the API from a browser.

    Local development needs the dev server. A deployment that serves the built
    interface from the same origin as the API needs no entry at all; one that
    splits them sets ``ALLOWED_ORIGINS`` to a comma-separated list.
    """
    configured = env.get("ALLOWED_ORIGINS")
    if configured:
        return [origin.strip() for origin in configured.split(",") if origin.strip()]
    return ["http://127.0.0.1:5180", "http://localhost:5180"]


