# Borrower-level records, the live queue and organisation data require a session.
# Aggregate portfolio reporting stays public: it is the marketing argument, and it
# exposes no individual borrower. That is the line a real product would draw.
PROTECTED_PREFIXES = ("/api/worklist", "/api/accounts")


@app.middleware("http")
async def gate_borrower_records(request: Request, call_next):
    path = request.url.path
    if request.method != "OPTIONS" and path.startswith(PROTECTED_PREFIXES):
        token = auth.bearer_token(request.headers.get("authorization"))
        user = None
        if token:
            connection = _connection()
            try:
                user = auth.user_for_token(connection, token)
            finally:
                connection.close()
        if user is None:
            return JSONResponse(
                {"detail": "Sign in to open borrower records."}, status_code=401
            )
        request.state.user = user
    return await call_next(request)


