@app.post("/api/triage")
async def triage(file: UploadFile = File(...)) -> dict[str, Any]:
    """Score an uploaded loan tape with the same engine, no integration required.

    This is the shortest honest path from "interesting" to "show me on my own data".
    """
    if not file.filename or not file.filename.lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Upload a .csv file.")

    raw = await file.read()
    await file.close()
    if not raw.strip():
        raise HTTPException(status_code=400, detail="The uploaded file is empty.")

    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = raw.decode("latin-1")

    reader = csv.DictReader(io.StringIO(text))
    if not reader.fieldnames:
        raise HTTPException(status_code=400, detail="The CSV has no header row.")

    normalised = {name.strip().lower().replace(" ", "_"): name for name in reader.fieldnames}
    required = {"borrower_name", "outstanding", "instalment", "dpd"}
    missing = sorted(required - set(normalised))
    if missing:
        raise HTTPException(
            status_code=400,
            detail=(
                "Missing required column(s): "
                + ", ".join(missing)
                + ". Required: borrower_name, outstanding, instalment, dpd. "
                "Optional: product, principal, arrears, monthly_inflow, inflow_change_pct."
            ),
        )

    def value(row: dict, key: str, default: float = 0.0) -> float:
        column = normalised.get(key)
        if column is None:
            return default
        raw_value = (row.get(column) or "").strip().replace(",", "").replace("\u20a6", "")
        if not raw_value:
            return default
        try:
            return float(raw_value)
        except ValueError:
            return default

    rows: list[dict] = []
    sampled = 0
    for index, row in enumerate(reader):
        if index >= 5000:
            break
        sampled += 1
        name_column = normalised["borrower_name"]
        name = (row.get(name_column) or f"Row {index + 2}").strip()
        dpd = int(max(0, value(row, "dpd")))
        instalment = max(0.0, value(row, "instalment"))
        outstanding = max(0.0, value(row, "outstanding"))
        arrears = value(row, "arrears") or (instalment if dpd > 0 else 0.0)
        inflow = value(row, "monthly_inflow")
        change = value(row, "inflow_change_pct", None) if normalised.get("inflow_change_pct") else None
        product = (row.get(normalised.get("product", ""), "") or "WC").strip().upper()[:3] or "WC"

        account = {
            "dpd": dpd,
            "arrears_amount": arrears,
            "instalment": instalment,
            "monthly_inflow_base": inflow,
            "instalments_paid": 0 if dpd > 0 else 1,
            "band": config.band_for_dpd(dpd),
            "product_code": product,
            "oldest_unpaid_due": "the uploaded tape",
            "short_payments_last_3": 0,
        }
        signals: list[dict] = []
        if change is not None and change <= -10:
            signals.append(
                {
                    "code": "inflow_decline",
                    "label": "Cash inflows falling",
                    "severity": 3 if change < -42 else 2,
                    "detected_at": config.AS_OF.isoformat(),
                    "headline": f"Average monthly inflows fell {abs(change):.0f}%",
                    "evidence": {"change_pct": change},
                    "lead_days": None,
                    "actionable": True,
                }
            )
        cashflow = (
            {
                "change_pct": change,
                "recent_3m_avg": inflow * (1 + (change or 0) / 100) if inflow else None,
                "prior_3m_avg": inflow if inflow else None,
            }
            if inflow or change is not None
            else None
        )

        risk = scoring.score_account(account, signals, cashflow)
        recommendation = playbooks.recommend(account, signals, risk, cashflow)
        value_engine = priority.evaluate(account, risk, recommendation["primary"], outstanding)

        rows.append(
            {
                "borrower_name": name,
                "product": product,
                "dpd": dpd,
                "band": account["band"],
                "band_label": config.BANDS[account["band"]]["label"],
                "outstanding": round(outstanding),
                "instalment": round(instalment),
                "arrears": round(arrears),
                "risk_index": risk["index"],
                "risk_band": risk["band_label"],
                "reasons": risk["reasons"][:3],
                "playbook": recommendation["primary"]["name"],
                "playbook_code": recommendation["primary"]["code"],
                "expected_recovery": value_engine["expected_recovery"],
                "loss_at_risk": value_engine["loss_at_risk"],
                "priority": value_engine["priority"],
                "exposure": round(outstanding),
                # Nested shapes so the ranking helper works identically for an
                # uploaded tape and the seeded book.
                "priority_value": value_engine,
                "risk": risk,
            }
        )

    if not rows:
        raise HTTPException(status_code=400, detail="The CSV contains no data rows.")

    ranking = priority.apply_review_budget(rows, None)
    book = sum(row["outstanding"] for row in rows)
    par30 = [row for row in rows if row["dpd"] >= 1]

    return {
        "accounts": len(rows),
        "book_outstanding": book,
        "par30": {
            "accounts": len(par30),
            "count_pct": round(len(par30) / len(rows) * 100, 1),
            "value_pct": round(
                sum(row["outstanding"] for row in par30) / max(1, book) * 100, 1
            ),
        },
        "expected_recovery_available": ranking["total_expected_recovery"],
        "ranking": ranking,
        "worklist": sorted(
            rows, key=lambda row: row["expected_recovery"], reverse=True
        )[:200],
        "note": (
            "Scored by the Northline Risk Index with the same weights used in the product. "
            "The upload is held in memory for this response only and is not stored."
        ),
    }
