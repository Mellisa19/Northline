@app.get("/api/accounts/{account_id}")
def account_detail(account_id: int) -> dict[str, Any]:
    connection = _connection()
    try:
        account = analytics.get_book_account(connection, account_id)
        if account is None:
            raise HTTPException(status_code=404, detail="Account not found")

        schedule = [
            dict(row)
            for row in connection.execute(
                "SELECT seq, due_date, amount_due, amount_paid, status FROM installments "
                "WHERE account_id = ? ORDER BY seq",
                (account_id,),
            ).fetchall()
        ]
        payments = [
            dict(row)
            for row in connection.execute(
                "SELECT paid_date, amount, channel, source FROM payments WHERE account_id = ? "
                "ORDER BY paid_date DESC LIMIT 40",
                (account_id,),
            ).fetchall()
        ]
        promises = [
            dict(row)
            for row in connection.execute(
                "SELECT id, made_at, promised_date, amount, status, resolved_at FROM promises "
                "WHERE account_id = ? ORDER BY made_at DESC",
                (account_id,),
            ).fetchall()
        ]
        actions = [
            dict(row)
            for row in connection.execute(
                "SELECT id, occurred_at, channel, disposition, officer, playbook_code, notes, "
                "cost, effect FROM actions WHERE account_id = ? ORDER BY occurred_at DESC LIMIT 40",
                (account_id,),
            ).fetchall()
        ]
        cashflow = [
            dict(row)
            for row in connection.execute(
                "SELECT month, inflow, outflow, closing_balance, pos_inflow, transfer_inflow, "
                "new_recurring_debits FROM cashflow_months WHERE account_id = ? ORDER BY month",
                (account_id,),
            ).fetchall()
        ]

        siblings = [
            {
                "id": row["id"],
                "ref": row["ref"],
                "product_name": row["product_name"],
                "outstanding_principal": row["outstanding_principal"],
                "dpd": row["dpd"],
                "status": row["status"],
            }
            for row in connection.execute(
                "SELECT id, ref, product_name, outstanding_principal, dpd, status FROM accounts "
                "WHERE borrower_id = ? AND id != ?",
                (account["borrower_id"], account_id),
            ).fetchall()
        ]

        return {
            "account": {
                key: value
                for key, value in account.items()
                if key not in ("signals", "actionable_signals", "cashflow")
            },
            "risk": account["risk"],
            "playbook": account["playbook"],
            "priority_value": account["priority_value"],
            "signals": account["signals"],
            "cashflow": account["cashflow"],
            "cashflow_series": cashflow,
            "schedule": schedule,
            "payments": payments,
            "promises": promises,
            "actions": actions,
            "siblings": siblings,
            "timeline": operations.account_timeline(connection, account_id),
        }
    finally:
        connection.close()


