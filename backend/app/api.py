@app.get("/api/portfolio/featured-case")
def featured_case() -> dict[str, Any]:
    """An anonymised worked example, for the public page.

    Borrower identity is replaced by a sector and city description. A marketing page
    has no business showing a named company's distress, and gating borrower records
    behind a session would be pointless if the site leaked one on the way in.
    """
    connection = _connection()
    try:
        row = connection.execute(
            "SELECT s.code, s.label, s.headline, s.detected_at, s.lead_days, s.severity, "
            "       a.id AS account_id, a.product_name, a.product_code, a.outstanding_principal, "
            "       a.dpd, b.sector, b.city "
            "FROM signal_events s JOIN accounts a ON a.id = s.account_id "
            "JOIN borrowers b ON b.id = a.borrower_id "
            "WHERE s.code = 'inflow_decline' AND s.lead_days > 20 AND a.dpd > 0 "
            "ORDER BY s.lead_days DESC LIMIT 1"
        ).fetchone()
        if row is None:
            raise HTTPException(status_code=404, detail="No worked example available.")

        series = [
            dict(item)
            for item in connection.execute(
                "SELECT month, inflow, closing_balance FROM cashflow_months "
                "WHERE account_id = ? ORDER BY month",
                (row["account_id"],),
            ).fetchall()
        ]
        account = analytics.get_book_account(connection, row["account_id"])
        change = ((account or {}).get("cashflow") or {}).get("change_pct")

        return {
            "descriptor": f"A {row['sector'].lower()} business in {row['city']}",
            "sector": row["sector"],
            "city": row["city"],
            "product_name": row["product_name"],
            "product_code": row["product_code"],
            "outstanding_principal": row["outstanding_principal"],
            "days_past_due": row["dpd"],
            "lead_days": row["lead_days"],
            "change_pct": change,
            "signal": {
                "code": row["code"],
                "label": row["label"],
                "headline": row["headline"],
                "detected_at": row["detected_at"],
                "severity": row["severity"],
            },
            "cashflow": series,
        }
    finally:
        connection.close()


